"""
Pure-Python PDF Report Generator for InterviewX.
Generates compliant, multi-page PDF documents for interview reports
without any external binary dependencies.
"""

import io
from typing import Dict, Any, List

class PDFReportGenerator:
    """Generates clean, professional PDF interview reports using pure Python."""

    @staticmethod
    def generate_interview_report_pdf(
        candidate_name: str,
        session_data: Dict[str, Any],
        questions_data: List[Dict[str, Any]]
    ) -> bytes:
        """
        Builds a multi-page PDF document detailing the candidate's interview performance.
        Returns bytes of the generated PDF.
        """
        writer = SimplePDFWriter()

        # Document Header
        writer.add_text("INTERVIEWX - CANDIDATE EVALUATION REPORT", size=18, bold=True, color=(0.1, 0.15, 0.4))
        writer.add_text("Practice. Get Honest Feedback. Improve. Get Hired.", size=10, italic=True, color=(0.4, 0.45, 0.5))
        writer.add_line()

        # Session Metadata Summary
        writer.add_text(f"Candidate: {candidate_name}", size=12, bold=True)
        writer.add_text(
            f"Target Role: {session_data.get('role_title', 'Software Engineer')}  |  "
            f"Tier: {session_data.get('difficulty', 'Intermediate')}",
            size=10
        )
        writer.add_text(
            f"Interview Round: {session_data.get('interview_type', 'Technical')}  |  "
            f"Date: {str(session_data.get('created_at', ''))[:16]}",
            size=10
        )
        writer.add_space(8)

        # Performance KPI Score Box
        ovr = session_data.get("overall_score", 0.0)
        acc = session_data.get("accuracy_score", 0.0)
        conc = session_data.get("conceptual_score", acc)
        rel = session_data.get("relevance_score", 0.0)
        clar = session_data.get("clarity_score", 0.0)
        readiness = session_data.get("readiness_assessment", "Placement Ready" if ovr >= 75 else "Needs Target Polish")

        writer.add_box_header("OVERALL EVALUATION SCORE", f"{ovr:.1f}% ({readiness})")
        writer.add_text(
            f"Accuracy: {acc:.1f}%  |  Conceptual: {conc:.1f}%  |  Relevance: {rel:.1f}%  |  Clarity: {clar:.1f}%",
            size=10, bold=True, color=(0.2, 0.25, 0.3)
        )
        writer.add_space(6)

        # Executive Summary
        writer.add_text("Executive Assessment:", size=11, bold=True)
        summary_text = session_data.get("summary", "Candidate completed evaluation session.")
        writer.add_paragraph(summary_text, size=9.5)
        writer.add_space(10)

        # Question by Question Breakdown
        writer.add_text("DETAILED QUESTION-BY-QUESTION EVALUATION", size=13, bold=True, color=(0.1, 0.15, 0.4))
        writer.add_line()

        for q in questions_data:
            q_num = q.get("question_number", 1)
            q_text = q.get("question_text", "")
            ans_text = q.get("user_answer", "No answer submitted.")
            q_score = q.get("overall_score", 0.0)
            feedback = q.get("honest_feedback", "")
            sample_ans = q.get("improved_answer", "")

            writer.add_text(f"Question {q_num}: {q_text}", size=10.5, bold=True, color=(0.05, 0.1, 0.2))
            writer.add_text(f"Question Score: {q_score:.1f}%  |  Category: {q.get('category', 'Technical')}", size=9, bold=True, color=(0.2, 0.3, 0.7))
            writer.add_space(3)

            writer.add_text("Candidate Answer:", size=9, bold=True)
            writer.add_paragraph(ans_text[:400] + ("..." if len(ans_text) > 400 else ""), size=8.5, indent=10)
            writer.add_space(3)

            writer.add_text("Honest Critique & Analysis:", size=9, bold=True, color=(0.6, 0.1, 0.1))
            writer.add_paragraph(feedback[:400] + ("..." if len(feedback) > 400 else ""), size=8.5, indent=10)
            writer.add_space(3)

            if sample_ans:
                writer.add_text("Improved Sample Answer (Tier-1 Standard):", size=9, bold=True, color=(0.1, 0.5, 0.2))
                writer.add_paragraph(sample_ans[:400] + ("..." if len(sample_ans) > 400 else ""), size=8.5, indent=10)

            writer.add_space(8)
            writer.add_separator()

        # Final Improvement Tips
        writer.add_space(8)
        writer.add_text("RECOMMENDED NEXT ACTIONS & TARGET POLISH", size=12, bold=True, color=(0.1, 0.15, 0.4))
        writer.add_paragraph("1. Review recurring misconceptions identified in this session.", size=9.5)
        writer.add_paragraph("2. Practice communicating structured definitions with explicit time and space complexities.", size=9.5)
        writer.add_paragraph("3. Visit the Personalised Preparation Roadmap page to generate a structured daily study plan.", size=9.5)
        writer.add_space(15)
        writer.add_text("Generated by InterviewX - AI Interview & Career Preparation Platform", size=8, italic=True, color=(0.5, 0.5, 0.5))

        return writer.build_pdf()


class SimplePDFWriter:
    """Lightweight pure-Python PDF 1.4 stream emitter."""

    def __init__(self):
        self.pages = []
        self.current_page_commands = []
        self.page_width = 595.0   # A4 width in points
        self.page_height = 842.0  # A4 height in points
        self.margin_x = 40.0
        self.current_y = 800.0
        self.bottom_margin = 45.0

    def _check_page_break(self, required_space: float = 20.0):
        """Starts a new page if remaining vertical height is insufficient."""
        if self.current_y - required_space < self.bottom_margin:
            self.pages.append(list(self.current_page_commands))
            self.current_page_commands = []
            self.current_y = 800.0

    def add_space(self, pts: float):
        self.current_y -= pts
        self._check_page_break(0)

    def add_line(self):
        self.add_space(4)
        y = self.current_y
        self.current_page_commands.append(f"0.75 w 0.8 0.85 0.9 RG {self.margin_x} {y:.2f} m {self.page_width - self.margin_x} {y:.2f} l S")
        self.add_space(8)

    def add_separator(self):
        y = self.current_y
        self.current_page_commands.append(f"0.5 w 0.9 0.9 0.92 RG {self.margin_x} {y:.2f} m {self.page_width - self.margin_x} {y:.2f} l S")
        self.add_space(8)

    def add_box_header(self, label: str, val: str):
        self._check_page_break(40)
        y = self.current_y
        box_h = 32.0
        # Draw background rectangle
        self.current_page_commands.append(
            f"0.95 0.96 0.98 rg {self.margin_x} {y - box_h:.2f} {self.page_width - 2 * self.margin_x} {box_h} re f"
        )
        self.current_page_commands.append(
            f"0.8 0.85 0.92 RG 1 w {self.margin_x} {y - box_h:.2f} {self.page_width - 2 * self.margin_x} {box_h} re S"
        )
        # Text inside box
        self.current_page_commands.append(
            f"BT /F2 9.5 Tf 0.3 0.35 0.45 rg {self.margin_x + 10} {y - 14:.2f} Td ({self._escape(label)}: ) Tj ET"
        )
        self.current_page_commands.append(
            f"BT /F2 12 Tf 0.1 0.45 0.25 rg {self.margin_x + 160} {y - 14:.2f} Td ({self._escape(val)}) Tj ET"
        )
        self.current_y -= (box_h + 8)

    def add_text(self, text: str, size: float = 10.0, bold: bool = False, italic: bool = False, color=(0.1, 0.1, 0.1)):
        self._check_page_break(size + 4)
        font_ref = "/F2" if bold else ("/F3" if italic else "/F1")
        r, g, b = color
        escaped = self._escape(text)
        cmd = f"BT {font_ref} {size} Tf {r:.2f} {g:.2f} {b:.2f} rg {self.margin_x} {self.current_y:.2f} Td ({escaped}) Tj ET"
        self.current_page_commands.append(cmd)
        self.current_y -= (size + 4)

    def add_paragraph(self, text: str, size: float = 9.0, indent: float = 0.0, color=(0.15, 0.15, 0.15)):
        """Wraps text into lines and renders paragraph."""
        r, g, b = color
        max_chars = int((self.page_width - 2 * self.margin_x - indent) / (size * 0.52))
        words = text.replace("\n", " ").split()
        lines = []
        current_line = []
        current_len = 0

        for word in words:
            if current_len + len(word) + 1 <= max_chars:
                current_line.append(word)
                current_len += len(word) + 1
            else:
                lines.append(" ".join(current_line))
                current_line = [word]
                current_len = len(word)
        if current_line:
            lines.append(" ".join(current_line))

        for line in lines:
            self._check_page_break(size + 3)
            escaped = self._escape(line)
            cmd = f"BT /F1 {size} Tf {r:.2f} {g:.2f} {b:.2f} rg {self.margin_x + indent} {self.current_y:.2f} Td ({escaped}) Tj ET"
            self.current_page_commands.append(cmd)
            self.current_y -= (size + 3)

    def _escape(self, s: str) -> str:
        """Escapes string for PDF literal text format."""
        s = s.replace("\\", "\\\\").replace("(", "\\(").replace(")", "\\)")
        # Replace non-ascii chars with nearest ascii
        return "".join([c if ord(c) < 128 else " " for c in s])

    def build_pdf(self) -> bytes:
        """Assembles all pages, fonts, streams, xref table, and trailer into PDF bytes."""
        if self.current_page_commands:
            self.pages.append(list(self.current_page_commands))

        if not self.pages:
            self.pages = [[]]

        out = io.BytesIO()
        out.write(b"%PDF-1.4\n%\xe2\xe3\xcf\xd3\n")

        offsets = []
        obj_count = 0

        def write_obj(content: bytes) -> int:
            nonlocal obj_count
            obj_count += 1
            offsets.append(out.tell())
            out.write(f"{obj_count} 0 obj\n".encode("ascii"))
            out.write(content)
            out.write(b"\nendobj\n")
            return obj_count

        # Obj 1: Catalog
        cat_id = 1
        # Obj 2: Pages root
        pages_root_id = 2

        # Obj 3, 4, 5: Standard Helvetica Fonts
        font_reg_id = 3
        font_bold_id = 4
        font_ital_id = 5

        # Reserve page object IDs
        page_obj_ids = []
        content_stream_ids = []
        for i in range(len(self.pages)):
            page_obj_ids.append(6 + i * 2)
            content_stream_ids.append(7 + i * 2)

        # Write Catalog
        write_obj(f"<< /Type /Catalog /Pages {pages_root_id} 0 R >>".encode("ascii"))

        # Write Pages Root
        kids_str = " ".join([f"{pid} 0 R" for pid in page_obj_ids])
        write_obj(f"<< /Type /Pages /Kids [{kids_str}] /Count {len(self.pages)} >>".encode("ascii"))

        # Write Fonts (Helvetica, Helvetica-Bold, Helvetica-Oblique)
        write_obj(b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>")
        write_obj(b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>")
        write_obj(b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Oblique >>")

        # Write Pages and Content Streams
        for i, page_cmds in enumerate(self.pages):
            p_id = page_obj_ids[i]
            c_id = content_stream_ids[i]

            stream_data = "\n".join(page_cmds).encode("latin-1", errors="ignore")

            # Page Object
            write_obj(
                f"<< /Type /Page /Parent {pages_root_id} 0 R /MediaBox [0 0 {self.page_width} {self.page_height}] "
                f"/Contents {c_id} 0 R "
                f"/Resources << /Font << /F1 {font_reg_id} 0 R /F2 {font_bold_id} 0 R /F3 {font_ital_id} 0 R >> >> >>".encode("ascii")
            )

            # Stream Object
            stream_obj = (
                f"<< /Length {len(stream_data)} >>\nstream\n".encode("ascii") +
                stream_data +
                b"\nendstream"
            )
            write_obj(stream_obj)

        # Cross-reference Table
        xref_offset = out.tell()
        out.write(b"xref\n")
        out.write(f"0 {obj_count + 1}\n".encode("ascii"))
        out.write(b"0000000000 65535 f \n")
        for off in offsets:
            out.write(f"{off:010d} 00000 n \n".encode("ascii"))

        # Trailer
        out.write(b"trailer\n")
        out.write(f"<< /Size {obj_count + 1} /Root {cat_id} 0 R >>\n".encode("ascii"))
        out.write(b"startxref\n")
        out.write(f"{xref_offset}\n".encode("ascii"))
        out.write(b"%%EOF\n")

        return out.getvalue()
